"""SQL profiling of the cleaned IMR Parquet with DuckDB (no load into Postgres needed).

    uv run python -m appeal_data.profile_duckdb      -> data/reports/imr_profile_duckdb.md
"""

from __future__ import annotations

from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[3]
PARQUET = ROOT / "data" / "processed" / "imr.parquet"
OUT = ROOT / "data" / "reports" / "imr_profile_duckdb.md"

QUERIES = {
    "Rows, years and outcome": """
        SELECT count(*) AS rows, min(year) AS first_year, max(year) AS last_year,
               round(avg(CASE WHEN overturned THEN 1 ELSE 0 END), 3) AS overturn_rate
        FROM imr""",
    "Overturn rate by IMR type": """
        SELECT type, count(*) AS n, round(avg(CASE WHEN overturned THEN 1 ELSE 0 END), 3) AS overturn_rate
        FROM imr GROUP BY type ORDER BY n DESC""",
    "Overturn rate by year (last 10 years)": """
        SELECT year, count(*) AS n, round(avg(CASE WHEN overturned THEN 1 ELSE 0 END), 3) AS overturn_rate
        FROM imr WHERE year >= (SELECT max(year) - 9 FROM imr) GROUP BY year ORDER BY year""",
    "Top 10 treatment categories": """
        SELECT treatment_category, count(*) AS n, round(avg(CASE WHEN overturned THEN 1 ELSE 0 END), 3) AS overturn_rate
        FROM imr GROUP BY treatment_category ORDER BY n DESC LIMIT 10""",
    "Treatment subcategories with at least 200 cases, highest and lowest overturn rates": """
        (SELECT treatment_subcategory, count(*) AS n, round(avg(CASE WHEN overturned THEN 1 ELSE 0 END), 3) AS overturn_rate
         FROM imr GROUP BY 1 HAVING count(*) >= 200 ORDER BY overturn_rate DESC LIMIT 5)
        UNION ALL
        (SELECT treatment_subcategory, count(*), round(avg(CASE WHEN overturned THEN 1 ELSE 0 END), 3)
         FROM imr GROUP BY 1 HAVING count(*) >= 200 ORDER BY 3 ASC LIMIT 5)""",
}


def _md(rel: duckdb.DuckDBPyRelation) -> str:
    cols = rel.columns
    rows = rel.fetchall()
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join("" if v is None else str(v) for v in r) + " |" for r in rows]
    return "\n".join(lines)


def main() -> None:
    if not PARQUET.exists():
        raise SystemExit(f"{PARQUET} not found: run `make data` first")
    con = duckdb.connect()
    con.execute(f"CREATE VIEW imr AS SELECT * FROM read_parquet('{PARQUET.as_posix()}')")
    cols = [r[0] for r in con.execute("DESCRIBE imr").fetchall()]
    need = {"year", "type", "overturned", "treatment_category", "treatment_subcategory"}
    missing = need - set(cols)
    if missing:
        raise SystemExit(f"columns missing from imr.parquet: {sorted(missing)} (have {cols})")
    parts = [
        "# IMR data profile (DuckDB SQL over the cleaned Parquet)",
        "",
        "Source: California DMHC Independent Medical Review determinations (CC BY). Generated by `appeal_data.profile_duckdb`.",
    ]
    for title, sql in QUERIES.items():
        parts += ["", f"## {title}", "", _md(con.sql(sql))]
    nulls = " UNION ALL ".join(f"SELECT '{c}' AS column, round(avg(CASE WHEN \"{c}\" IS NULL THEN 1 ELSE 0 END), 4) AS null_rate FROM imr" for c in cols)
    parts += ["", "## Null rate per column", "", _md(con.sql(nulls + " ORDER BY null_rate DESC"))]
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
